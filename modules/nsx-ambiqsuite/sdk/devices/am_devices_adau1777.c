// ****************************************************************************
//
//  Deinitialize IOM I2C
//
// ****************************************************************************
uint32_t am_devices_adau1777_i2c_deinit(uint32_t ui32Module)
{
    if (ui32Module > AM_REG_IOM_NUM_MODULES)
    {
        return AM_DEVICES_ADAU1777_STATUS_OUT_OF_RANGE;
    }

    am_bsp_iom_pins_disable(ui32Module, AM_HAL_IOM_I2C_MODE);

    if (g_adau1777_IOMHandle != NULL)
    {
        //
        // Disable the IOM.
        //
        if (am_hal_iom_disable(g_adau1777_IOMHandle) )
        {
            return AM_DEVICES_ADAU1777_STATUS_INVALID_HANDLE;
        }

        //
        // Disable power to and uninitialize the IOM instance.
        //
        if (am_hal_iom_power_ctrl(g_adau1777_IOMHandle, AM_HAL_SYSCTRL_DEEPSLEEP, false) )
        {
            return AM_DEVICES_ADAU1777_STATUS_HW_ERR;
        }

        if (am_hal_iom_uninitialize(g_adau1777_IOMHandle) )
        {
            return AM_DEVICES_ADAU1777_STATUS_FAIL;
        }

        g_adau1777_IOMHandle = NULL;
    }

    return AM_DEVICES_ADAU1777_STATUS_SUCCESS;
}

uint32_t am_devices_adau1777_set_sample_rate(uint8_t chip_addr, uint32_t sample_rate)
{
    uint32_t state = AM_DEVICES_ADAU1777_STATUS_SUCCESS;
    ADI_REG_TYPE r50_ser_portfs_ic_1 = 0;
    state = am_devices_adau1777_i2c_read(chip_addr, REG_SAI_0_IC_1_ADDR, (uint32_t *)&r50_ser_portfs_ic_1, REG_SAI_0_IC_1_BYTE);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }

    r50_ser_portfs_ic_1 &= ~R50_SER_PORT_FS_IC_1_MASK;
    switch (sample_rate)
    {
        case 48000:
            r50_ser_portfs_ic_1 |= (0 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 8000:
            r50_ser_portfs_ic_1 |= (1 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 12000:
            r50_ser_portfs_ic_1 |= (2 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 16000:
            r50_ser_portfs_ic_1 |= (3 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 24000:
            r50_ser_portfs_ic_1 |= (4 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 32000:
            r50_ser_portfs_ic_1 |= (5 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 96000:
            r50_ser_portfs_ic_1 |= (6 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        case 192000:
            r50_ser_portfs_ic_1 |= (7 << R50_SER_PORT_FS_IC_1_SHIFT);
            break;

        default:
            return AM_DEVICES_ADAU1777_STATUS_INVALID_ARG;
    }

    return SIGMA_WRITE_REGISTER_BLOCK(chip_addr, REG_SAI_0_IC_1_ADDR, REG_SAI_0_IC_1_BYTE, &r50_ser_portfs_ic_1);
}

