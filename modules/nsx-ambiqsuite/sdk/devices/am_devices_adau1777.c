uint32_t am_devices_adau1777_set_linear_gain(uint8_t chip_addr, uint8_t value)
{
    uint32_t     state = AM_DEVICES_ADAU1777_STATUS_SUCCESS;
    ADI_REG_TYPE control_data[4] = {0};

    // Validate gain parameter range: 0 to 15 (0dB to 15dB)
    if (value > 15)
    {
        return AM_DEVICES_ADAU1777_STATUS_INVALID_ARG;
    }

    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG0_STAGE0_B0_ADDR, 4, &linear_gain[value][0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }

    // Enable PGA, activate gain trigger, configure soft switching
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG0_STAGE0_B1_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG0_STAGE0_B2_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG0_STAGE0_A2_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }

    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG1_STAGE0_B0_ADDR, 4, &linear_gain[value][0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }

    // Enable PGA, activate gain trigger, configure soft switching
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG1_STAGE0_B1_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG1_STAGE0_B2_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }
    state = SIGMA_WRITE_REGISTER_BLOCK(chip_addr, MOD_GAIN1_ALG1_STAGE0_A2_ADDR, sizeof(control_data), &control_data[0]);
    if (state != AM_DEVICES_ADAU1777_STATUS_SUCCESS)
    {
        return state;
    }

    return state;
}
