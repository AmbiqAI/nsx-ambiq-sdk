//! @file am_devices_adau1777.c
//!
//! @brief Analog Devices ADAU1777 Digital Audio Amplifier Driver with I2C Interface.
//!
//! @addtogroup devices_adau1777 ADAU1777 I2C Audio Amplifier Driver
//! @ingroup devices
//! @{
//!
//! Purpose: This module provides a comprehensive hardware abstraction layer
//!          for the Analog Devices ADAU1777 digital audio amplifier. The driver
//!          enables high-performance audio playback with extensive configuration
//!          options through I2C control interface. It supports wide sample rate
//!          ranges, multiple audio interface modes, and gain
//!          control. Configuration tables are generated using Analog Devices'
//!          SigmaStudio tool for optimal audio performance and system integration.
//!
//! @section devices_adau1777_features Key Features
//!
//! 1. @b High-Performance @b Audio @b Amplification: Digital Class-D amplifier with superior audio quality.
//! 2. @b Wide @b Sample @b Rate @b Support: 8kHz to 192kHz sample rates for diverse audio applications.
//! 3. @b Flexible @b Audio @b Interfaces: Stereo modes.
//! 4. @b BclkRate @b Configuration: 16bclks/channel, 32bclks/channel support.
//! 5. @b Programmable @b Gain @b Control: Software-controlled volume adjustment.
//! 6. @b SigmaStudio @b Integration: Uses configuration tables generated by SigmaStudio tool.
//! 7. @b I2C @b Interface: Standard I2C communication for control and configuration.
//!
//! @section devices_adau1777_functionality Functionality
//!
//! - Initialize and configure ADAU1777 amplifier via I2C interface
//! - Configure wide range of audio sample rates (8kHz to 192kHz)
//! - Set audio interface mode (Stereo I2S)
//! - Configure I2S frame width(16bclks/channel, 32bclks/channel)
//! - Control amplifier gain for volume adjustment
//! - Load SigmaStudio-generated configuration tables
//! - Handle register-level configuration with read/write operations
//! - Support full reset and initialization sequences
//!
//! @section devices_adau1777_usage Usage
//!
//! 1. Initialize I2C interface with am_devices_adau1777_i2c_init()
//! 2. Initialize ADAU1777 device with am_devices_adau1777_init()
//! 3. Configure sample rate with am_devices_adau1777_set_sample_rate()
//! 4. Set audio interface mode with am_devices_adau1777_set_sai_ms()
//! 5. Configure i2s parameters with am_devices_adau1777_set_bclk_rate()
//! 6. Adjust dac volume with am_devices_adau1777_set_dac_0_volume(), am_devices_adau1777_set_dac_1_volume()
//! 7. Mute dac with am_devices_adau1777_mute_dac_0(), am_devices_adau1777_mute_dac_1()
//! 8. Play audio through configured amplifier
//! 9. Deinitialize device with am_devices_adau1777_deinit()
//! 10. Deinitialize I2C interface with am_devices_adau1777_i2c_deinit()
//!
//! @section devices_adau1777_configuration Configuration
//!
//! - Set up I2C interface parameters and timing
//! - Configure audio sample rates based on system requirements
//! - Set up audio interface mode (Stereo) for system topology
//! - Load SigmaStudio-generated configuration tables
//! - Set up gain control ranges and behavior
//! - Optimize register settings for specific audio applications
//
