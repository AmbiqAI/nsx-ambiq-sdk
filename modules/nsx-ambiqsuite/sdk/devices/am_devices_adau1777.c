// As SIGMA_WRITE_REGISTER_BLOCK is exported by SigmaStudio tool, so reserve it.
static uint32_t SIGMA_WRITE_REGISTER_BLOCK(uint8_t dev_addr, uint16_t reg,
                                           uint16_t data_len, ADI_REG_TYPE *data)
{
    return am_devices_adau1777_i2c_write(dev_addr, reg, (uint32_t *)data, data_len);
}

uint32_t am_devices_adau1777_i2c_read(uint32_t dev_addr, uint16_t reg_addr,
                                     uint32_t *p_buf, uint32_t size)
{
    am_hal_iom_transfer_t Transaction;

    Transaction.ui8Priority        = 1;
    Transaction.ui32InstrLen       = 2;
    Transaction.ui64Instr          = reg_addr;
    Transaction.eDirection         = AM_HAL_IOM_RX;
    Transaction.ui32NumBytes       = size;
    Transaction.pui32RxBuffer      = p_buf;
    Transaction.bContinue          = false;
    Transaction.ui8RepeatCount     = 0;
    Transaction.ui32PauseCondition = 0;
    Transaction.ui32StatusSetClr   = 0;

    Transaction.uPeerInfo.ui32I2CDevAddr = dev_addr;
    if (am_hal_iom_blocking_transfer(g_adau1777_IOMHandle, &Transaction) !=
        AM_HAL_STATUS_SUCCESS)
    {
        return AM_DEVICES_ADAU1777_STATUS_INVALID_OPERATION;
    }

    return AM_DEVICES_ADAU1777_STATUS_SUCCESS;
}

uint32_t am_devices_adau1777_i2c_write(uint32_t dev_addr, uint16_t reg_addr,
                                      uint32_t *p_buf, uint32_t size)
{
    am_hal_iom_transfer_t Transaction;

    Transaction.ui8Priority        = 1;
    Transaction.ui32InstrLen       = 2;
    Transaction.ui64Instr          = reg_addr;
    Transaction.eDirection         = AM_HAL_IOM_TX;
    Transaction.ui32NumBytes       = size;
    Transaction.pui32TxBuffer      = p_buf;
    Transaction.bContinue          = false;
    Transaction.ui8RepeatCount     = 0;
    Transaction.ui32PauseCondition = 0;
    Transaction.ui32StatusSetClr   = 0;

    Transaction.uPeerInfo.ui32I2CDevAddr = dev_addr;
    if (am_hal_iom_blocking_transfer(g_adau1777_IOMHandle, &Transaction) !=
        AM_HAL_STATUS_SUCCESS)
    {
        return AM_DEVICES_ADAU1777_STATUS_INVALID_OPERATION;
    }

    return AM_DEVICES_ADAU1777_STATUS_SUCCESS;
}

// ****************************************************************************
//
//  Initialize IOM I2C
//
// ****************************************************************************
uint32_t am_devices_adau1777_i2c_init(uint32_t             ui32Module,
                                     am_hal_iom_config_t *psIOMSettings)
{
    if (ui32Module > AM_REG_IOM_NUM_MODULES)
    {
        return AM_DEVICES_ADAU1777_STATUS_OUT_OF_RANGE;
    }

    if (g_adau1777_IOMHandle != NULL)
    {
        return AM_DEVICES_ADAU1777_STATUS_IN_USE;
    }

    //
    // Configure the IOM pins.
    //
    am_bsp_iom_pins_enable(ui32Module, AM_HAL_IOM_I2C_MODE);

    //
    // Initialize the IOM instance.
    // Enable power to the IOM instance.
    // Configure the IOM for Serial operation during initialization.
    // Enable the IOM.
    // HAL Success return is 0
    //
    if (am_hal_iom_initialize(ui32Module, &g_adau1777_IOMHandle) ||
        am_hal_iom_power_ctrl(g_adau1777_IOMHandle, AM_HAL_SYSCTRL_WAKE,
                              false) ||
        am_hal_iom_configure(g_adau1777_IOMHandle, psIOMSettings) ||
        am_hal_iom_enable(g_adau1777_IOMHandle))
    {
        return AM_DEVICES_ADAU1777_STATUS_HW_ERR;
    }

    return AM_DEVICES_ADAU1777_STATUS_SUCCESS;
}

